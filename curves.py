def get_edge_point(side, size=64):
    """
    Returns a random point on the specified edge.
    side: 0=top, 1=right, 2=bottom, 3=left
    """
    if side == 0:  # top
        return (random.randint(0, size-1), 0)
    elif side == 1:  # right
        return (size-1, random.randint(0, size-1))
    elif side == 2:  # bottom
        return (random.randint(0, size-1), size-1)
    else:  # left (side == 3)
        return (0, random.randint(0, size-1))

def cubic_bezier(t, p0, p1, p2, p3):
    """B(t) calculation for cubic Bezier"""
    x0, y0 = p0
    x1, y1 = p1
    x2, y2 = p2
    x3, y3 = p3
    term0 = (1 - t)**3
    term1 = 3 * (1 - t)**2 * t
    term2 = 3 * (1 - t) * t**2
    term3 = t**3
    x = term0 * x0 + term1 * x1 + term2 * x2 + term3 * x3
    y = term0 * y0 + term1 * y1 + term2 * y2 + term3 * y3
    return (x, y)

def generate_curve_image(size=(64, 64)):
    img = Image.new('L', size, color=0)
    draw = ImageDraw.Draw(img)
    width, height = size[0], size[1]

    # Choose two different random sides (0=top, 1=right, 2=bottom, 3=left)
    start_side = random.randint(0, 3)
    end_side = random.randint(0, 3)
    while end_side == start_side:
        end_side = random.randint(0, 3)

    # Get endpoints on chosen sides
    p0 = get_edge_point(start_side, width)
    p3 = get_edge_point(end_side, width)

    # Generate control points that create smooth curves
    # Place them roughly 1/3 and 2/3 along the path with some variation
    p1_x = p0[0] + (p3[0] - p0[0]) * 0.33 + random.uniform(-20, 20)
    p1_y = p0[1] + (p3[1] - p0[1]) * 0.33 + random.uniform(-20, 20)
    p1 = (p1_x, p1_y)

    p2_x = p0[0] + (p3[0] - p0[0]) * 0.67 + random.uniform(-20, 20)
    p2_y = p0[1] + (p3[1] - p0[1]) * 0.67 + random.uniform(-20, 20)
    p2 = (p2_x, p2_y)

    # Generate curve points
    points = []
    steps = 60
    for i in range(steps + 1):
        t = i / steps
        points.append(cubic_bezier(t, p0, p1, p2, p3))

    draw.line(points, fill=255, width=1)
    return img

def generate_curve_dataset(n=5000, size=64):
    """
    Generates N images of size (size, size).
    Curves connect ANY two sides (including same side, adjacent sides, opposite sides).
    Returns:
       - images: numpy array of shape (N, size, size)
       - labels: numpy array of shape (N,)
    """
    print(f"Generating {n} curve images ({size}x{size})...")
    print(f"Curves connect any two different sides (no same-side curves)")

    # Initialize arrays
    images = np.zeros((n, size, size), dtype=np.uint8)
    labels = np.zeros(n, dtype=np.int64)

    for i in range(n):
        img = generate_curve_image((size, size))
        images[i] = np.array(img)
        labels[i] = 0

    print("Generation complete.")
    return images, labels

