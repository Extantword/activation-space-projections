from PIL import Image
from IPython.display import HTML, display
from google.colab import output

def create_depth_explorer(latents_3d, image_volume_uint8, x_vals, y_vals, z_vals):
    """
    Explorer with Drop Lines/Guide Lines to solve 3D perspective confusion.
    """

    # 1. SETUP BOUNDS
    u1_min, u1_max = float(x_vals.min()), float(x_vals.max())
    u2_min, u2_max = float(y_vals.min()), float(y_vals.max())
    u3_min, u3_max = float(z_vals.min()), float(z_vals.max())

    grid_size = image_volume_uint8.shape[0]

    # Downsample background
    if len(latents_3d) > 3000:
        idx = np.random.choice(len(latents_3d), 3000, replace=False)
        display_latents = latents_3d[idx]
    else:
        display_latents = latents_3d

    latents_list = display_latents.tolist()

    # --------------------------------------------------------
    # 2. PYTHON CALLBACK
    # --------------------------------------------------------
    def get_grid_image(u1, u2, u3):
        ix = int(np.clip((u1 - u1_min) / (u1_max - u1_min) * (grid_size - 1), 0, grid_size - 1))
        iy = int(np.clip((u2 - u2_min) / (u2_max - u2_min) * (grid_size - 1), 0, grid_size - 1))
        iz = int(np.clip((u3 - u3_min) / (u3_max - u3_min) * (grid_size - 1), 0, grid_size - 1))

        img_arr = image_volume_uint8[ix, iy, iz]
        img = Image.fromarray(img_arr).resize((300, 300), Image.NEAREST)
        buffer = io.BytesIO()
        img.save(buffer, format='PNG')
        return base64.b64encode(buffer.getvalue()).decode('utf-8')

    output.register_callback('get_grid_image', get_grid_image)

    # --------------------------------------------------------
    # 3. HTML/JS
    # --------------------------------------------------------
