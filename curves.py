class ConvAutoencoder(nn.Module):
    def __init__(self, latent_dim, activation=nn.ReLU, n=64, use_batch_norm=True, dropout_rate=0.0):
        """
        Symmetric Convolutional Autoencoder for 64x64 input
        """
        super(ConvAutoencoder, self).__init__()

        self.n = n
        self.latent_dim = latent_dim
        self.use_batch_norm = use_batch_norm
        self.dropout_rate = dropout_rate

        # -----------------------
        # ENCODER
        # -----------------------
        encoder_layers = []

        # Conv1: 1x64x64 -> 32x32x32
        encoder_layers.append(('conv1', nn.Conv2d(1, 32, kernel_size=3, stride=2, padding=1)))
        if use_batch_norm: encoder_layers.append(('bn1', nn.BatchNorm2d(32)))
        encoder_layers.append(('act1', activation()))
        if dropout_rate > 0: encoder_layers.append(('drop1', nn.Dropout2d(p=dropout_rate)))

        # Conv2: 32x32x32 -> 64x16x16
        encoder_layers.append(('conv2', nn.Conv2d(32, 64, kernel_size=3, stride=2, padding=1)))
        if use_batch_norm: encoder_layers.append(('bn2', nn.BatchNorm2d(64)))
        encoder_layers.append(('act2', activation()))
        if dropout_rate > 0: encoder_layers.append(('drop2', nn.Dropout2d(p=dropout_rate)))

        # Conv3: 64x16x16 -> 128x8x8
        encoder_layers.append(('conv3', nn.Conv2d(64, 128, kernel_size=3, stride=2, padding=1)))
        if use_batch_norm: encoder_layers.append(('bn3', nn.BatchNorm2d(128)))
        encoder_layers.append(('act3', activation()))
        if dropout_rate > 0: encoder_layers.append(('drop3', nn.Dropout2d(p=dropout_rate)))

        # Conv4: 128x8x8 -> 256x4x4
        encoder_layers.append(('conv4', nn.Conv2d(128, 256, kernel_size=3, stride=2, padding=1)))
        if use_batch_norm: encoder_layers.append(('bn4', nn.BatchNorm2d(256)))
        encoder_layers.append(('act4', activation()))
        if dropout_rate > 0: encoder_layers.append(('drop4', nn.Dropout2d(p=dropout_rate)))

        self.conv_encoder = nn.Sequential(OrderedDict(encoder_layers))

        # Flattening 256 channels * 4 * 4 spatial
        flattened_size = 256 * 4 * 4  # Equals 4096

        self.flatten = nn.Flatten()

        # Fully connected to latent space
        self.fc_encoder = nn.Linear(flattened_size, latent_dim)

        # -----------------------
        # DECODER
        # -----------------------

        # Fully connected from latent space
        self.fc_decoder = nn.Linear(latent_dim, flattened_size)
        self.act_fc = activation()

        # Unflatten: 4096 -> 256x4x4
        self.unflatten = nn.Unflatten(1, (256, 4, 4))

        decoder_layers = []

        # TransposeConv1: 256x4x4 -> 128x8x8
        decoder_layers.append(('deconv1', nn.ConvTranspose2d(256, 128, kernel_size=3, stride=2, padding=1, output_padding=1)))
        if use_batch_norm: decoder_layers.append(('bn_dec1', nn.BatchNorm2d(128)))
        decoder_layers.append(('act_dec1', activation()))
        if dropout_rate > 0: decoder_layers.append(('drop_dec1', nn.Dropout2d(p=dropout_rate)))

        # TransposeConv2: 128x8x8 -> 64x16x16
        decoder_layers.append(('deconv2', nn.ConvTranspose2d(128, 64, kernel_size=3, stride=2, padding=1, output_padding=1)))
        if use_batch_norm: decoder_layers.append(('bn_dec2', nn.BatchNorm2d(64)))
        decoder_layers.append(('act_dec2', activation()))
        if dropout_rate > 0: decoder_layers.append(('drop_dec2', nn.Dropout2d(p=dropout_rate)))

        # TransposeConv3: 64x16x16 -> 32x32x32
        decoder_layers.append(('deconv3', nn.ConvTranspose2d(64, 32, kernel_size=3, stride=2, padding=1, output_padding=1)))
        if use_batch_norm: decoder_layers.append(('bn_dec3', nn.BatchNorm2d(32)))
        decoder_layers.append(('act_dec3', activation()))
        if dropout_rate > 0: decoder_layers.append(('drop_dec3', nn.Dropout2d(p=dropout_rate)))

        # TransposeConv4: 32x32x32 -> 1x64x64
        decoder_layers.append(('deconv4', nn.ConvTranspose2d(32, 1, kernel_size=3, stride=2, padding=1, output_padding=1)))
        decoder_layers.append(('sigmoid', nn.Sigmoid()))

        self.conv_decoder = nn.Sequential(OrderedDict(decoder_layers))

    def encode(self, x):
        # Expects x to be (Batch, 1, 64, 64) or (Batch, 4096)
        if x.dim() == 2:
            x = x.view(-1, 1, self.n, self.n)

        x = self.conv_encoder(x)
        x = self.flatten(x)
        latent = self.fc_encoder(x)
        return latent

    def decode(self, latent):
        x = self.fc_decoder(latent)
        x = self.act_fc(x)
        x = self.unflatten(x)
        x = self.conv_decoder(x)
        return x.view(-1, self.n * self.n)  # Flatten output to (Batch, 4096)

    def forward(self, x):
        latent = self.encode(x)
        reconstructed = self.decode(latent)
        return reconstructed


