def get_random_point(width, height, margin=0):
    x = random.randint(-margin, width + margin)
    y = random.randint(-margin, height + margin)
    return (x, y)

def cubic_bezier(t, p0, p1, p2, p3):
    """B(t) calculation for cubic Bezier"""
    x0, y0 = p0
    x1, y1 = p1
    x2, y2 = p2
    x3, y3 = p3
    term0 = (1 - t)**3
    term1 = 3 * (1 - t)**2 * t
    term2 = 3 * (1 - t) * t**2
    term3 = t**3
    x = term0 * x0 + term1 * x1 + term2 * x2 + term3 * x3
    y = term0 * y0 + term1 * y1 + term2 * y2 + term3 * y3
    return (x, y)

def generate_curve_image(size=(64, 64)):
    img = Image.new('L', size, color=0)
    draw = ImageDraw.Draw(img)
    width, height = size

    # Random starting point on left edge (x=0, y=random)
    p0_y = random.randint(0, 63)
    p0 = (0, p0_y)

    # Random ending point on right edge (x=63, y=random)
    p3_y = random.randint(0, 63)
    p3 = (63, p3_y)

    # Control points with moderate variation
    # They progress left-to-right but allow vertical curves

    # p1: first third horizontally
    p1_x = random.uniform(15, 25)
    # Vertically interpolate between start and end, with variation
    p1_y_base = p0_y + (p3_y - p0_y) * 0.33
    p1_y = p1_y_base + random.uniform(-20, 20)
    p1 = (p1_x, p1_y)

    # p2: second third horizontally
    p2_x = random.uniform(38, 48)
    # Vertically interpolate between start and end, with variation
    p2_y_base = p0_y + (p3_y - p0_y) * 0.67
    p2_y = p2_y_base + random.uniform(-20, 20)
    p2 = (p2_x, p2_y)

    points = []
    steps = 60
    for i in range(steps + 1):
        t = i / steps
        points.append(cubic_bezier(t, p0, p1, p2, p3))

    draw.line(points, fill=255, width=1)
    return img

