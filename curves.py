        # Move data to device
        data = data.to(device)

        # Zero gradients
        optimizer.zero_grad()

        # Forward pass
        outputs = model(data)

        # Compute loss (Input == Target for Autoencoders)
        loss = criterion(outputs, data)

        # Backward pass and optimize
        loss.backward()
        optimizer.step()

        running_loss += loss.item()

