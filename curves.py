def get_random_point(width, height, margin=0):
    x = random.randint(-margin, width + margin)
    y = random.randint(-margin, height + margin)
    return (x, y)

def cubic_bezier(t, p0, p1, p2, p3):
    """B(t) calculation for cubic Bezier"""
    x0, y0 = p0
    x1, y1 = p1
    x2, y2 = p2
    x3, y3 = p3
    term0 = (1 - t)**3
    term1 = 3 * (1 - t)**2 * t
    term2 = 3 * (1 - t) * t**2
    term3 = t**3
    x = term0 * x0 + term1 * x1 + term2 * x2 + term3 * x3
    y = term0 * y0 + term1 * y1 + term2 * y2 + term3 * y3
    return (x, y)

def generate_curve_image(size=(64, 64)):
    img = Image.new('L', size, color=0)
    draw = ImageDraw.Draw(img)
    width, height = size

    # Fixed endpoints: (0,0) to (63,63)
    p0 = (0, 0)
    p3 = (63, 63)

    # Random control points for variety
    control_spread = 30
    p1 = get_random_point(width, height, margin=control_spread)
    p2 = get_random_point(width, height, margin=control_spread)

    points = []
    steps = 60
    for i in range(steps + 1):
        t = i / steps
        points.append(cubic_bezier(t, p0, p1, p2, p3))

    draw.line(points, fill=255, width=1)
    return img

def generate_curve_dataset(n=5000, size=64):
    """
    Generates N images of size (size, size).
    All curves start at (0,0) and end at (63,63) with random control points.
    Returns:
       - images: numpy array of shape (N, size, size)
       - labels: numpy array of shape (N,)
    """
    print(f"Generating {n} curve images ({size}x{size})...")
    print(f"All curves: start (0,0) → end (63,63)")

    # Initialize arrays
    images = np.zeros((n, size, size), dtype=np.uint8)
    labels = np.zeros(n, dtype=np.int64)

    for i in range(n):
        img = generate_curve_image((size, size))
        images[i] = np.array(img)
        labels[i] = 0

    print("Generation complete.")
    return images, labels

